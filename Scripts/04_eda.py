"""
04_eda.py  --  exploratory data analysis for the report (Person A, Step 3).

Read-only on the data. Reads the four split files in data/processed/ and writes:
    reports/eda_summary.md           tables you can paste into the report
    reports/figures/*.png            charts for the report

It reads each file in chunks and keeps only small facts (label, project, length), so
it needs little memory.

Usage (one line):
    python Scripts/04_eda.py
"""
import argparse
import os
import sys

import pandas as pd

try:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
except ImportError:
    sys.exit("matplotlib is missing. Run:  pip install matplotlib   then run this again.")

FILES = [("train", "bigvul_train.csv.gz"), ("val", "bigvul_val.csv.gz"),
         ("test", "bigvul_test.csv.gz"), ("cvefixes_external", "cvefixes_external.csv.gz")]


def load_facts(path, chunksize):
    parts = []
    for ch in pd.read_csv(path, dtype=str, chunksize=chunksize):
        code = ch["code"].fillna("")
        parts.append(pd.DataFrame({
            "label": ch["label"].astype(int),
            "project_key": ch["project_key"],
            "language": ch["language"],
            "date": ch["date"],
            "chars": code.str.len(),
            "lines": code.str.count("\n") + 1,
        }))
    return pd.concat(parts, ignore_index=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", default="data/processed")
    ap.add_argument("--report", default="reports/eda_summary.md")
    ap.add_argument("--fig-dir", default="reports/figures")
    ap.add_argument("--chunksize", type=int, default=20000)
    a = ap.parse_args()
    os.makedirs(a.fig_dir, exist_ok=True)
    os.makedirs(os.path.dirname(a.report) or ".", exist_ok=True)

    facts = {}
    for name, fn in FILES:
        p = os.path.join(a.data_dir, fn)
        if not os.path.exists(p):
            sys.exit(f"ERROR: {p} not found. Run 03_make_splits.py first.")
        print(f"Reading {fn} ...", flush=True)
        facts[name] = load_facts(p, a.chunksize)
    bv = pd.concat([facts[k].assign(split=k) for k in ["train", "val", "test"]], ignore_index=True)
    cf = facts["cvefixes_external"]

    md = ["# Exploratory data analysis", "",
          "Generated by Scripts/04_eda.py from the frozen split files. Nothing was modified.", ""]

    # ---- 1. class balance per split
    rows = []
    for k, d in facts.items():
        v = int(d["label"].sum())
        rows.append([k, f"{len(d):,}", f"{v:,}", f"{len(d)-v:,}", f"{v/len(d):.1%}"])
    md += ["## 1. Class balance", "",
           "| Split | Rows | Vulnerable | Not vulnerable | % vulnerable |", "|---|---|---|---|---|"]
    md += ["| " + " | ".join(r) + " |" for r in rows]
    maj = 1 - bv["label"].mean()
    md += ["", f"A model that always answers 'not vulnerable' scores **{maj:.1%} accuracy on BigVul** "
               f"and **{1-cf['label'].mean():.1%} on CVEfixes** while finding nothing. "
               "This is why the report uses precision, recall, F1 and PR-AUC.", ""]

    fig, ax = plt.subplots(figsize=(7, 4))
    names = list(facts.keys())
    safe = [int((facts[k]["label"] == 0).sum()) for k in names]
    vuln = [int((facts[k]["label"] == 1).sum()) for k in names]
    ax.bar(names, safe, label="not vulnerable", color="#9bb7d4")
    ax.bar(names, vuln, bottom=safe, label="vulnerable", color="#c8553d")
    for i, k in enumerate(names):
        ax.text(i, safe[i] + vuln[i], f"{vuln[i]/(safe[i]+vuln[i]):.1%}", ha="center", va="bottom", fontsize=9)
    ax.set_ylabel("functions"); ax.set_title("Class balance by split (label: % vulnerable)")
    ax.legend(); fig.tight_layout(); fig.savefig(os.path.join(a.fig_dir, "class_balance.png"), dpi=150); plt.close(fig)

    # ---- 2. code length
    md += ["## 2. Code length (characters and lines)", "",
           "| Dataset | Label | Median chars | 95th pct chars | Max chars | Median lines |", "|---|---|---|---|---|---|"]
    for dname, d in [("BigVul", bv), ("CVEfixes", cf)]:
        for lab, lname in [(0, "not vulnerable"), (1, "vulnerable")]:
            s = d[d["label"] == lab]
            md.append(f"| {dname} | {lname} | {s['chars'].median():,.0f} | {s['chars'].quantile(.95):,.0f} | "
                      f"{s['chars'].max():,} | {s['lines'].median():,.0f} |")
    over = (bv["chars"] > 2000).mean()
    md += ["", f"About **{over:.0%} of BigVul functions are longer than 2,000 characters**. CodeBERT reads at most "
               "512 tokens, so those will be cut. Person B should measure real token lengths before choosing "
               "the input length.", ""]

    fig, ax = plt.subplots(figsize=(7, 4))
    bins = [10 ** (x / 4) for x in range(4, 25)]
    for lab, c, n in [(0, "#9bb7d4", "not vulnerable"), (1, "#c8553d", "vulnerable")]:
        ax.hist(bv.loc[bv["label"] == lab, "chars"].clip(lower=10), bins=bins, alpha=0.65, color=c, label=n, density=True)
    ax.set_xscale("log"); ax.set_xlabel("characters per function (log scale)"); ax.set_ylabel("share of functions")
    ax.set_title("BigVul: code length by label"); ax.legend()
    fig.tight_layout(); fig.savefig(os.path.join(a.fig_dir, "code_length.png"), dpi=150); plt.close(fig)

    # ---- 3. projects
    md += ["## 3. Projects (BigVul, all splits)", "",
           f"- Distinct projects: **{bv['project_key'].nunique()}**",
           f"- Chrome share: **{(bv['project_key']=='chrome').mean():.0%}**, "
           f"linux share: **{(bv['project_key']=='linux').mean():.0%}**", "",
           "| Project | Rows | % of BigVul | Vulnerable | % vulnerable |", "|---|---|---|---|---|"]
    pt = bv.groupby("project_key").agg(rows=("label", "size"), vul=("label", "sum")).sort_values("rows", ascending=False)
    top = pt.head(12)
    for p, r in top.iterrows():
        md.append(f"| {p} | {r['rows']:,} | {r['rows']/len(bv):.1%} | {int(r['vul']):,} | {r['vul']/r['rows']:.1%} |")
    md.append("")
    fig, ax = plt.subplots(figsize=(7, 4.5))
    t = top.iloc[::-1]
    ax.barh(t.index, t["rows"], color="#9bb7d4")
    for i, (p, r) in enumerate(t.iterrows()):
        ax.text(r["rows"], i, f"  {r['vul']/r['rows']:.1%} vuln", va="center", fontsize=8)
    ax.set_xlabel("functions"); ax.set_title("BigVul: 12 biggest projects (label: % vulnerable)")
    ax.set_xlim(0, t["rows"].max() * 1.25)
    fig.tight_layout(); fig.savefig(os.path.join(a.fig_dir, "top_projects.png"), dpi=150); plt.close(fig)

    # ---- 4. language and dates
    md += ["## 4. Language and dates", "", "| Dataset | C | C++ | rows with no date |", "|---|---|---|---|"]
    for dname, d in [("BigVul", bv), ("CVEfixes", cf)]:
        md.append(f"| {dname} | {(d['language']=='C').sum():,} | {(d['language']=='C++').sum():,} | {int(d['date'].isna().sum()):,} |")
    md += ["", "Undated BigVul rows are not a problem for the commit-grouped split, but a date-based split "
               "could not place them.", ""]

    # ---- 5. split balance check
    md += ["## 5. Do the three BigVul splits look alike?", "",
           "| Split | Median chars | Chrome % | linux % | C++ % |", "|---|---|---|---|---|"]
    for k in ["train", "val", "test"]:
        d = facts[k]
        md.append(f"| {k} | {d['chars'].median():,.0f} | {(d['project_key']=='chrome').mean():.0%} | "
                  f"{(d['project_key']=='linux').mean():.0%} | {(d['language']=='C++').mean():.0%} |")
    md.append("")

    text = "\n".join(md)
    with open(a.report, "w", encoding="utf-8") as f:
        f.write(text)
    print("\n" + text)
    print(f"\nSaved {a.report} and charts in {a.fig_dir}/")


if __name__ == "__main__":
    main()