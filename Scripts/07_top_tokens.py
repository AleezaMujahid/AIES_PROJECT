"""
07_top_tokens.py -- which tokens does the baseline treat as suspicious? (Person B, Step 2)

Read-only. Loads models/baseline/baseline.joblib and lists the tokens with the largest
Logistic Regression weights:
  - positive weight: pushes a function towards "vulnerable"
  - negative weight: pushes it towards "safe"
Writes reports/baseline_top_tokens.md for the report.

Why it matters: it makes the model explainable, and it shows whether the model learned
real code patterns (strcpy, memcpy, length, sizeof) or shortcuts such as project-specific names.

Usage:  python Scripts/07_top_tokens.py
        python Scripts/07_top_tokens.py --top 40
"""
import argparse
import os
import sys

import joblib
import numpy as np


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model-dir", default="models/baseline")
    ap.add_argument("--top", type=int, default=30)
    ap.add_argument("--report", default="reports/baseline_top_tokens.md")
    a = ap.parse_args()
    p = os.path.join(a.model_dir, "baseline.joblib")
    if not os.path.exists(p):
        sys.exit(f"ERROR: {p} not found. Run 06_train_baseline.py first.")
    b = joblib.load(p)
    names = np.array(b["vectorizer"].get_feature_names_out())
    w = b["model"].coef_[0]
    order = np.argsort(w)
    pos = order[::-1][: a.top]
    neg = order[: a.top]

    md = ["# Baseline: most influential tokens", "",
          "Generated by Scripts/07_top_tokens.py. A larger positive weight pushes a function towards "
          "'vulnerable'; a negative weight pushes it towards 'safe'. Tokens made of two words are pairs "
          "that appear next to each other.", "",
          "| Rank | Towards vulnerable | Weight | Towards safe | Weight |", "|---|---|---|---|---|"]
    for i in range(a.top):
        md.append(f"| {i+1} | `{names[pos[i]]}` | {w[pos[i]]:+.2f} | `{names[neg[i]]}` | {w[neg[i]]:+.2f} |")
    md += ["", "How to read it for the report: tokens such as memory and length handling "
               "(for example memcpy, sizeof, len) suggest the model learned real code patterns. "
               "Names that belong to one project (for example chrome-specific identifiers) suggest "
               "a shortcut: the model learned which project a function comes from."]
    os.makedirs(os.path.dirname(a.report) or ".", exist_ok=True)
    with open(a.report, "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    print("\n".join(md))
    print(f"\nSaved {a.report}")


if __name__ == "__main__":
    main()