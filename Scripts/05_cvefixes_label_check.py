"""
05_cvefixes_label_check.py  --  how trustworthy are the CVEfixes labels? (Person A, Step 4)

CVEfixes label: before_change=True -> label 1, False -> label 0. That only says the function
is the version BEFORE a fix commit changed it. It does not prove the function contained the bug.

This script (read-only) measures two things from the data:
  A. PAIRS: how many functions appear in the same commit + file with BOTH a before (1) and an
     after (0) version. Those are the cleanest examples of "this function was fixed".
  B. COMMIT SIZE: how many functions each fix commit changed. If a commit changed 1-3
     functions, a label-1 function is very likely the fixed one. If it changed 40, most of
     them are probably not the vulnerable one.
Then it writes a 50-function sample for you to read by hand.

Outputs
    reports/cvefixes_label_stats.md        numbers for the report
    reports/cvefixes_review_sample.txt     50 functions to read (25 label 1, 25 label 0)
    reports/cvefixes_review_sheet.csv      fill in one verdict per function
    data/processed/cvefixes_external_strict.csv.gz   the strict test set (see section C of the report)

Usage (one line):
    python Scripts/05_cvefixes_label_check.py
"""
import argparse
import os
import sys

import pandas as pd

SHOW_CHARS = 1500


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cvefixes", default="data/processed/cvefixes_external.csv.gz")
    ap.add_argument("--manifest", default="data/processed/split_manifest.csv")
    ap.add_argument("--n", type=int, default=50, help="functions to review (half label 1, half label 0)")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--report", default="reports/cvefixes_label_stats.md")
    ap.add_argument("--sample", default="reports/cvefixes_review_sample.txt")
    ap.add_argument("--sheet", default="reports/cvefixes_review_sheet.csv")
    ap.add_argument("--strict-out", default="data/processed/cvefixes_external_strict.csv.gz")
    ap.add_argument("--max-commit-funcs", type=int, default=10,
                    help="strict set: keep only commits that changed at most this many label-1 functions")
    a = ap.parse_args()
    for p in (a.cvefixes, a.manifest):
        if not os.path.exists(p):
            sys.exit(f"ERROR: {p} not found. Run 03_make_splits.py first.")
    os.makedirs("reports", exist_ok=True)

    cf = pd.read_csv(a.cvefixes, dtype=str)
    cf["label"] = cf["label"].astype(int)
    man = pd.read_csv(a.manifest, dtype=str,
                      usecols=["sample_id", "cve_id", "cwe_id"]).drop_duplicates("sample_id")
    cf = cf.merge(man, on="sample_id", how="left")
    cf["func_name"] = cf["func_name"].fillna("")
    cf["file"] = cf.get("file", pd.Series([""] * len(cf)))

    # ---------- A. pairs
    key = ["commit_id", "file", "func_name"]
    named = cf[cf["func_name"] != ""].copy()
    g = named.groupby(key)["label"].agg(["min", "max", "size"]).reset_index()
    pairs = g[(g["min"] == 0) & (g["max"] == 1)]
    paired_rows = int(pairs["size"].sum())
    only1 = int(((g["min"] == 1) & (g["max"] == 1)).sum())
    only0 = int(((g["min"] == 0) & (g["max"] == 0)).sum())

    # ---------- B. commit size (number of label-1 functions per commit)
    n1 = cf[cf["label"] == 1].groupby("commit_id").size()
    cf["commit_n1"] = cf["commit_id"].map(n1).fillna(0).astype(int)
    one = cf[cf["label"] == 1]
    bins = [(1, 1, "1"), (2, 3, "2-3"), (4, 10, "4-10"), (11, 10 ** 9, "11 or more")]
    size_rows = []
    for lo, hi, name in bins:
        m = (one["commit_n1"] >= lo) & (one["commit_n1"] <= hi)
        size_rows.append((name, int(m.sum()), m.mean()))
    small = int(((one["commit_n1"] >= 1) & (one["commit_n1"] <= 3)).sum())

    md = ["# CVEfixes label check", "",
          "Generated by Scripts/05_cvefixes_label_check.py. Nothing was modified.", "",
          f"- CVEfixes external rows: **{len(cf):,}** ({int(cf['label'].sum()):,} label 1, "
          f"{int((cf['label']==0).sum()):,} label 0)",
          f"- Label-1 functions: **{len(one):,}** in **{one['commit_id'].nunique():,}** commits", "",
          "## A. Before/after pairs", "",
          f"- Functions (same commit, file and name) that have **both** a before and an after version: "
          f"**{len(pairs):,}** ({paired_rows:,} rows, {paired_rows/len(cf):.1%} of the set)",
          f"- Functions that appear only as 'before' (label 1): {only1:,}",
          f"- Functions that appear only as 'after' (label 0): {only0:,}",
          f"- Rows with no function name (cannot be paired): {int((cf['func_name']=='').sum()):,}", "",
          "## B. How many functions does each fix commit change?", "",
          "| Label-1 functions in the commit | Label-1 rows | % of label-1 rows |", "|---|---|---|"]
    md += [f"| {n} | {c:,} | {p:.1%} |" for n, c, p in size_rows]
    md += ["", f"**{small/max(len(one),1):.0%} of label-1 rows come from commits that changed 1 to 3 functions**, "
               "where the label is most believable. Rows from commits that changed 11 or more functions are "
               "the least certain.", ""]
    # ---------- strict set: paired functions from small fix commits
    paired_keys = pairs[key]
    cf["_paired"] = cf.merge(paired_keys.assign(_p=1), on=key, how="left")["_p"].fillna(0).astype(int).values
    strict = cf[(cf["_paired"] == 1) & (cf["commit_n1"] >= 1) & (cf["commit_n1"] <= a.max_commit_funcs)]
    strict_out = strict.drop(columns=["_paired", "commit_n1", "cve_id", "cwe_id"])
    strict_out.to_csv(a.strict_out, index=False, compression="gzip")
    md += ["## C. Strict CVEfixes test set", "",
           f"Rule: the function has both a before and an after version, and its commit changed at most "
           f"{a.max_commit_funcs} label-1 functions.", "",
           f"- Strict rows: **{len(strict):,}** ({int(strict['label'].sum()):,} label 1, "
           f"{int((strict['label']==0).sum()):,} label 0), from {strict['commit_id'].nunique():,} commits, "
           f"{strict['project_key'].nunique():,} projects",
           f"- Saved to `{a.strict_out}`",
           "- The strict set is close to 50% vulnerable because every function appears twice. "
           "PR-AUC from it is not comparable with BigVul's; compare it only against the baseline on the same set.", ""]
    with open(a.report, "w", encoding="utf-8") as f:
        f.write("\n".join(md))

    # ---------- the 50 functions to read
    half = a.n // 2
    s1 = cf[cf["label"] == 1].sample(min(half, int((cf["label"] == 1).sum())), random_state=a.seed)
    s0 = cf[cf["label"] == 0].sample(min(half, int((cf["label"] == 0).sum())), random_state=a.seed)
    samp = pd.concat([s1, s0]).sample(frac=1, random_state=a.seed).reset_index(drop=True)
    samp.insert(0, "n", range(1, len(samp) + 1))

    out = ["CVEfixes review sample. For each function decide a verdict (see rubric at the bottom).", ""]
    for _, r in samp.iterrows():
        code = str(r["code"])
        cut = code if len(code) <= SHOW_CHARS else code[:SHOW_CHARS] + f"\n    ...[cut, {len(code):,} characters in total]"
        out += ["=" * 72,
                f"#{r['n']}   label: {r['label']}  ({'BEFORE the fix' if r['label']==1 else 'AFTER the fix'})",
                f"project: {r['project_key']}   commit: {r['commit_id']}",
                f"CVE: {r['cve_id']}   CWE: {r['cwe_id']}   function: {r['func_name']}   file: {r['file']}",
                f"label-1 functions changed in this commit: {r['commit_n1']}",
                "-" * 72, cut, ""]
    out += ["=" * 72, "RUBRIC (write one letter per function in cvefixes_review_sheet.csv)", "",
            "  Y = this function looks like it could contain the security problem (or is the clearly fixed one)",
            "  N = this function looks unrelated (formatting, rename, comment, logging, helper)",
            "  ? = cannot tell without the patch",
            "",
            "Tip: you do not need to find the exact bug. Ask: does this look like code that parses input,",
            "copies memory, checks sizes, or handles pointers? Or just plumbing?"]
    with open(a.sample, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    samp[["n", "sample_id", "label", "project_key", "commit_id", "commit_n1"]].assign(
        verdict="", note="").to_csv(a.sheet, index=False)

    print("\n".join(md))
    print(f"\nSaved {a.report}, {a.sample}, {a.sheet} and {a.strict_out}")


if __name__ == "__main__":
    main()